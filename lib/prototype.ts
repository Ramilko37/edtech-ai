export function routeKey(query: string): CourseKey | null {
  const q = query.toLowerCase();

  if (/информат|компьютер|алгоритм|\bкод|данны|программ/.test(q)) {
    return "cs";
  }

  if (/критич|филосо|мышлен|аргумент|логик|занудств/.test(q)) {
    return "crit";
  }

  if (/ai|нейросет|искусствен|gpt|чат|промпт|grok|llm/.test(q)) {
    return "ai";
  }

  return null;
}
